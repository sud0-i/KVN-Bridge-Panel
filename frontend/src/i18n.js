function initialLang () {
  try {
    const saved = localStorage.getItem('lang')
    if (saved === 'ru' || saved === 'en') return saved
  } catch (e) { /* хранилище может быть недоступно */ }
  return (navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

export const lang = ref(initialLang())

export function setLang (value) {
  lang.value = value
  try { localStorage.setItem('lang', value) } catch (e) { /* не страшно */ }
}

// t('key') или t('key', { ip: '1.2.3.4' }) — подставляет {ip}
export function t (key, params = {}) {
  let value = key.split('.').reduce((o, k) => (o ? o[k] : undefined), messages[lang.value])
  if (value === undefined) value = key
  return String(value).replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '')
}
